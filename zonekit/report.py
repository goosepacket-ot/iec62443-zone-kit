    rules = "".join(
        f"<tr><td>{e(r['conduit'])}</td><td><b style='color:{'#1e8449' if r['action']=='ALLOW' else '#c0392b'}'>{r['action']}</b></td>"
        f"<td>{e(r['source_zone'])}</td><td>{e(r['dest_zone'])}</td><td>{e(r['protocol'])}</td><td>{e(r['port'])}</td>"
        f"<td>{e(r['purpose'])}</td></tr>" for r in model["matrix"])
