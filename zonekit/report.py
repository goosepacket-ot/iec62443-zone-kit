"""Write the zone/conduit outputs: firewall CSV, Mermaid, DOT, Markdown and HTML reports, JSON."""
from __future__ import annotations

import csv
import html
import json
import os

from . import build, diagram
from .model import Asset, Conduit, Flow, Zone

STATUS_COLOR = {"gap": "#c0392b", "partial": "#d68910", "review": "#2874a6", "ok": "#1e8449"}


def assemble(assets: list[Asset], flows: list[Flow], source: str = "") -> dict:
    zones = build.build_zones(assets)
    conduits = build.build_conduits(flows, assets, zones)
    return {
        "source": source,
        "zones": zones,
        "conduits": conduits,
        "flows": flows,
        "matrix": build.firewall_matrix(conduits),
        "assessment": build.assess(zones, conduits, flows),
        "sl": build.sl_summary(zones),
    }


def write_all(model: dict, out_dir: str) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    zones, conduits = model["zones"], model["conduits"]
    paths = []

    def _w(name, text):
        p = os.path.join(out_dir, name)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        paths.append(p)

    _w("zones.mmd", diagram.mermaid(zones, conduits))
    _w("zones.dot", diagram.dot(zones, conduits))

    p = os.path.join(out_dir, "firewall-rules.csv")
    with open(p, "w", newline="", encoding="utf-8") as f:
        cols = ["conduit", "action", "source_zone", "dest_zone", "protocol", "port", "direction", "purpose"]
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(model["matrix"])
    paths.append(p)

    _w("report.md", markdown(model))
    _w("report.html", html_report(model))

    p = os.path.join(out_dir, "model.json")
    with open(p, "w", encoding="utf-8") as f:
        json.dump(_jsonable(model), f, indent=2)
    paths.append(p)
    return paths


def _jsonable(model: dict) -> dict:
    return {
        "source": model["source"],
        "zones": [{"name": z.name, "level": z.level, "sl_t": z.sl_t,
                   "assets": [a.__dict__ for a in z.assets]} for z in model["zones"].values()],
        "conduits": [{"src": c.src_zone, "dst": c.dst_zone,
                      "flows": [f.__dict__ for f in c.flows]} for c in model["conduits"]],
        "firewall_rules": model["matrix"],
        "assessment": model["assessment"],
        "sl_summary": model["sl"],
    }


def markdown(model: dict) -> str:
    zones, conduits = model["zones"], model["conduits"]
    L = [f"# IEC 62443 zone & conduit model — {os.path.basename(model['source']) or 'site'}", "",
         f"- Zones: **{len(zones)}**, conduits: **{len(conduits)}**, defined flows: **{len(model['flows'])}**",
         "", "## Zones and suggested SL-T", "",
         "| Zone | Purdue level | Assets | Criticality | Suggested SL-T |", "|---|---|---:|---|:---:|"]
    for s in model["sl"]:
        L.append(f"| {s['zone']} | {s['level'] or '-'} | {s['assets']} | {s['criticality']} | **{s['suggested_sl_t']}** |")
    L += ["", "> SL-T is a **starting suggestion** from asset criticality, to be confirmed by a risk assessment per IEC 62443-3-2.",
          "", "## Conduits", ""]
    for c in conduits:
        L.append(f"### {c.src_zone} ⟷ {c.dst_zone}")
        for fl in c.flows:
            L.append(f"- {fl.src} → {fl.dst}: **{fl.protocol or 'any'}**"
                     f"{(' ' + fl.port) if fl.port else ''} — {fl.purpose or '(no purpose stated)'} ({fl.direction})")
        L.append("")
    L += ["## Firewall rule matrix", "", "| Conduit | Action | Source | Dest | Protocol | Port | Purpose |",
          "|---|---|---|---|---|---|---|"]
    for r in model["matrix"]:
        L.append(f"| {r['conduit']} | {r['action']} | {r['source_zone']} | {r['dest_zone']} | "
                 f"{r['protocol']} | {r['port']} | {r['purpose']} |")
    L += ["", "## Foundational requirement checklist (IEC 62443-3-3)", ""]
    for a in model["assessment"]:
        L += [f"### {a['fr']} — {a['title']}  `[{a['status'].upper()}]`",
              f"{a['description']}", "", f"{a['note']}", ""]
    L += ["## Zone & conduit diagram (Mermaid)", "", "```mermaid", diagram.mermaid(zones, conduits), "```", "",
          "_Generated by iec62443-zone-kit. This is a working model to drive an assessment, not a certification. "
          "Confirm zones, SL-T and flows with a formal IEC 62443-3-2 risk assessment._", ""]
    return "\n".join(L)


